// Post-build step: writes public/sw.js, a small service worker that keeps the generator
// working offline. It precaches the home page, the hashed build assets and the app icons.
// Signed-in pages, short links and the API always go to the network.
//
// The cache name is a hash of everything precached, so each deploy installs a fresh cache
// and removes the old one.
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

function walk(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const toUrl = (root, prefix) => (file) => `${prefix}/${relative(root, file).split(sep).join("/")}`;

const assets = walk(".next/static").map(toUrl(".next/static", "/_next/static"));
const icons = walk("public/icons").map(toUrl("public", ""));
const pages = ["/", "/manifest.webmanifest", "/icon.svg", "/favicon.ico", "/apple-icon.png"];
const urls = [...pages, ...icons, ...assets];

const hash = createHash("sha256");
hash.update(readFileSync(".next/BUILD_ID"));
for (const file of [...walk(".next/static"), ...walk("public/icons")].sort())
  hash.update(readFileSync(file));
const version = hash.digest("hex").slice(0, 12);

const worker = `// Generated by scripts/generate-sw.mjs. Do not edit.
const CACHE = "quickqreate-${version}";
const PRECACHE = ${JSON.stringify(urls)};
const NETWORK_ONLY = /^\\/(r|R|api|auth|dashboard|account|login|signup|forgot-password)(\\/|$)/;

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((k) => k.startsWith("quickqreate-") && k !== CACHE).map((k) => caches.delete(k))),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  const url = new URL(request.url);
  if (request.method !== "GET" || url.origin !== self.location.origin || NETWORK_ONLY.test(url.pathname)) return;

  // Pages: network first so updates and sign-in state show immediately; the cached
  // generator page when offline.
  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok && url.pathname === "/") {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put("/", copy));
          }
          return response;
        })
        .catch(() => caches.match("/")),
    );
    return;
  }

  // Build assets are content-hashed, so cache first is safe.
  event.respondWith(
    caches.match(request, { ignoreSearch: true }).then(
      (cached) =>
        cached ??
        fetch(request).then((response) => {
          if (response.ok && url.pathname.startsWith("/_next/static/")) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        }),
    ),
  );
});
`;

writeFileSync("public/sw.js", worker);
console.log(`Service worker: ${urls.length} files precached (cache quickqreate-${version})`);
