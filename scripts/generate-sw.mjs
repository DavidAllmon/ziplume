// Post-build step: writes out/sw.js, a small service worker that precaches every file in the
// static export so QuickQReate works offline. Runs automatically after `npm run build`.
//
// The cache name is derived from a hash of the exported files, so every deploy installs a
// fresh cache and old ones are removed on activation.
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";

const OUT = "out";
const base = process.env.NEXT_PUBLIC_BASE_PATH ?? "";
// Social images and README logos are fetched by link unfurlers and GitHub, never by the app.
const SKIP = [/^sw\.js$/, /^(opengraph|twitter)-image/, /^brand\//, /^404\.html$/, /^_not-found/];

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((entry) => {
      const path = join(dir, entry.name);
      return entry.isDirectory() ? walk(path) : [path];
    }),
  );
  return files.flat();
}

const hash = createHash("sha256");
const urls = [];
for (const file of (await walk(OUT)).sort()) {
  const path = relative(OUT, file).split(sep).join("/");
  if (SKIP.some((pattern) => pattern.test(path))) continue;
  hash.update(path).update(await readFile(file));
  urls.push(`${base}/${path}`);
}
urls.push(`${base}/`);

const version = hash.digest("hex").slice(0, 12);

const worker = `// Generated by scripts/generate-sw.mjs. Do not edit.
const CACHE = "quickqreate-${version}";
const INDEX = "${base}/index.html";
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith("quickqreate-") && key !== CACHE)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;

  // Pages: network first so updates show up immediately, cached copy when offline.
  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          if (response.ok) caches.open(CACHE).then((cache) => cache.put(INDEX, copy));
          return response;
        })
        .catch(() => caches.match(INDEX)),
    );
    return;
  }

  // Assets are content-hashed or versioned with the cache, so cache first is safe.
  event.respondWith(
    caches.match(request, { ignoreSearch: true }).then(
      (cached) =>
        cached ??
        fetch(request).then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        }),
    ),
  );
});
`;

await writeFile(join(OUT, "sw.js"), worker);
console.log(`Service worker: ${urls.length} files precached (cache quickqreate-${version})`);
